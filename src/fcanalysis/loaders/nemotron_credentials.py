def credential_kind(name: str, field: str, definition: dict[str, Any]) -> _Kind | None:
    """Select a reviewed consuming signature; unknown signatures abstain."""
    parameters = definition.get("parameters")
    properties = (
        parameters.get("properties", {}) if isinstance(parameters, dict) else {}
    )
    schema = properties.get(field) if isinstance(properties, dict) else None
    if not isinstance(schema, dict):
        return None
    description = schema.get("description")
    default = schema.get("default")
    if not isinstance(description, str) or not (
        default is None or isinstance(default, str)
    ):
        return None
    key = (name, field, description, default)
    if key in _DIGITS_INPUTS:
        return "digits"
    if key in _BEARER_INPUTS:
        return "bearer"
    if key in _LITERAL_INPUTS:
        return "literal"
    return None


def visible_spelled_digits(value: str, texts: list[str]) -> bool:
    """Match only complete, hyphen-separated individual OTP digits.

    Numeric signs, decimals, and prefixes/suffixes of longer sequences are not
    evidence. Password and API-key consumers never select this representation.
    """
    if re.fullmatch(r"[0-9]{4,8}", value) is None:
        return False
    # Consume whole runs before checking boundaries. Starting a regex at each
    # target digit could otherwise accept a spaced suffix of a longer code.
    for text in texts:
        for match in re.finditer(r"[0-9](?:[ \t]*-[ \t]*[0-9]){3,}", text):
            prefix = text[: match.start()]
            suffix = text[match.end() :]
            if re.search(r"[\w.,+\-]$", prefix) or prefix.rstrip(" \t").endswith(
                ("+", "-")
            ):
                continue
            if re.match(r"\w|[.,]\d|[ \t]*-[ \t]*\d", suffix):
                continue
            if re.sub(r"[ \t-]", "", match.group()) == value:
                return True
    return False
